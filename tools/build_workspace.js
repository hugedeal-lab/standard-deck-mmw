// Bundle the Design Pass runtime the agent's workspace artifact loads into
// one file, design-pass/workspace/dist/design-pass.js: check, ui, extract,
// merge and workspace, in that order. One CDN request instead of five.
// Usage: node tools/build_workspace.js
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const parts = ['design-pass/checker/check.js', 'design-pass/checker/ui.js', 'design-pass/checker/extract.js',
  'design-pass/checker/merge.js', 'design-pass/workspace/workspace.js'];
const out = '// GENERATED by tools/build_workspace.js -- do not edit. Sources: ' + parts.join(', ') + '\n' +
  parts.map((p) => '\n// ---- ' + p + ' ----\n' + fs.readFileSync(path.join(ROOT, p), 'utf8')).join('\n');
fs.mkdirSync(path.join(ROOT, 'design-pass/workspace/dist'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'design-pass/workspace/dist/design-pass.js'), out);
console.log('wrote design-pass/workspace/dist/design-pass.js (' + Math.round(out.length / 1024) + ' KB)');
